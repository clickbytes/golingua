package learning

import (
	"errors"
	"fmt"

	"github.com/clickbytes/golingua/internal/features"
	"github.com/clickbytes/golingua/internal/morph"
	"github.com/clickbytes/golingua/internal/provenance"
)

// NewRecord constructs a one-cell correction from an explicitly generated
// baseline. It does not derive lexical or provenance data beyond that input.
func NewRecord(
	id, datasetID, datasetVersion, baselineDigest, corrected, initiatedBy, recordedAt, reviewedBy, reviewedAt, previousID string,
	author provenance.SourceRef,
	base morph.GeneratedForm,
) (Record, error) {
	if base.Source != morph.ExceptionSourceRegular || base.ExceptionID != "" {
		return Record{}, errors.New("cannot create a correction over a baseline generated by an existing exception")
	}
	if corrected == base.Surface {
		return Record{}, errors.New("corrected form must differ from the baseline surface")
	}

	featuresCopy := cloneFeatureValues(base.Features)
	selectorFeatures := make([]morph.ExceptionFeatureMatch, 0, len(featuresCopy))
	for _, feature := range featuresCopy {
		if feature.State == features.StateKnown {
			selectorFeatures = append(selectorFeatures, morph.ExceptionFeatureMatch{
				Feature: feature.Feature,
				Value:   feature.Value,
			})
		}
	}

	baselineCopy := cloneGeneratedForm(base)
	rule := morph.ExceptionRule{
		SchemaVersion: morph.ExceptionSchemaVersion,
		ID:            morph.ExceptionID(id),
		Scope:         morph.ExceptionScopeLexemeCell,
		Selector: morph.ExceptionSelector{
			Language:   base.Language,
			POS:        base.POS,
			ParadigmID: base.ParadigmID,
			LexemeID:   base.LexemeID,
			CellID:     base.CellID,
			Features:   selectorFeatures,
		},
		Effect:     morph.ExceptionEffect{Kind: morph.ExceptionEffectReplace, Forms: []string{corrected}},
		Provenance: author,
		ReviewedBy: reviewedBy,
		ReviewedAt: reviewedAt,
	}
	record := Record{
		ID:                   id,
		DatasetID:            datasetID,
		DatasetVersion:       datasetVersion,
		Language:             base.Language,
		ProfileVersion:       base.ProfileVersion,
		BaselineDigest:       baselineDigest,
		Features:             featuresCopy,
		BaselineForm:         baselineCopy,
		Rule:                 rule,
		OriginalForm:         base.Surface,
		CorrectedForm:        corrected,
		InitiatedBy:          initiatedBy,
		PreviousCorrectionID: previousID,
		Author:               author,
		RecordedAt:           recordedAt,
		Active:               true,
	}
	if err := validateRecord(record); err != nil {
		return Record{}, fmt.Errorf("invalid correction record: %w", err)
	}
	return record, nil
}

func cloneFeatureValues(values []features.FeatureValue) []features.FeatureValue {
	if values == nil {
		return nil
	}
	cloned := make([]features.FeatureValue, len(values))
	copy(cloned, values)
	for index, value := range cloned {
		if value.Variable != nil {
			variable := *value.Variable
			cloned[index].Variable = &variable
		}
	}
	return cloned
}

func cloneGeneratedForm(form morph.GeneratedForm) morph.GeneratedForm {
	form.Features = cloneFeatureValues(form.Features)
	if form.Provenance != nil {
		provenanceCopy := *form.Provenance
		form.Provenance = &provenanceCopy
	}
	if form.Trace != nil {
		trace := make([]morph.GenerationTraceStep, len(form.Trace))
		copy(trace, form.Trace)
		for index, step := range trace {
			if step.Applied != nil {
				applied := *step.Applied
				trace[index].Applied = &applied
			}
		}
		form.Trace = trace
	}
	return form
}
